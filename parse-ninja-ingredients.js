// Форматы: "400г курица", "2 ст.л. масло", "4 зубчика чеснока", "½ ч.л. соли"
function parseLine(line) {
  // Убираем объяснение после тире
  const clean = line.replace(/\s*[—–-]\s*.+$/, '').trim();
  if (!clean) return null;

  // Дроби
  const fractions = { '½': 0.5, '¼': 0.25, '¾': 0.75, '⅓': 0.33, '⅔': 0.67, '⅛': 0.125 };
  let text = clean;
  for (const [f, v] of Object.entries(fractions)) {
    text = text.replace(f, v + ' ');
  }

  // Единицы
  const UNITS = ['ст\\.л\\.', 'ч\\.л\\.', 'кг', 'мл', 'л', 'г', 'шт', 'зуб\\.', 'банка', 'банок', 'банки', 'пачка', 'лист', 'листа', 'листов', 'стебел', 'ломт', 'полоск', 'головка'];
  const unitRx = new RegExp(`^(\\d+(?:[.,]\\d+)?)\\s*(${UNITS.join('|')})\\.?\\s+(.+)$`, 'i');
  const numFirstRx = /^(\d+(?:[.,]\d+)?)\s+(.+)$/;

  let m = text.match(unitRx);
  if (m) {
    return { amount: parseFloat(m[1].replace(',', '.')), unit: m[2].replace(/\\/g,''), name: m[3] };
  }

  m = text.match(numFirstRx);
  if (m) {
    return { amount: parseFloat(m[1]), unit: 'шт', name: m[2] };
  }

  // Без количества — специи и т.п.
  return { amount: 1, unit: 'по вкусу', name: clean };
}

// ──── ПОИСК ЦЕНЫ ────
function findPrice(name) {
  const nl = name.toLowerCase();
  for (const entry of PRICE_DB) {
    if (entry.keys.some(k => nl.includes(k.toLowerCase()))) {
      return entry;
    }
  }
  return null;
}

function getUnitPrice(entry, unit) {
  const unitNorm = (unit || 'шт').toLowerCase().replace(/\.$/, '');
  // Try exact match
  if (entry.unit_map[unitNorm]) return entry.unit_map[unitNorm];
  // Aliases
  const aliases = {
    'гр': 'г', 'gram': 'г',
    'ml': 'мл', 'л': 'л',
    'шт': 'шт', 'piece': 'шт',
    'ст.л': 'ст.л.', 'ст л': 'ст.л.', 'tbsp': 'ст.л.',
    'ч.л': 'ч.л.', 'ч л': 'ч.л.', 'tsp': 'ч.л.',
    'зуб': 'зуб.', 'зубч': 'зуб.',
    'банок': 'банка', 'банки': 'банка',
    'листа': 'лист', 'листов': 'лист',
    'ломт': 'ломт', 'ломтик': 'ломт',
    'полоска': 'полоск', 'полосок': 'полоск',
    'стебель': 'стебел',
  };
  const ua = aliases[unitNorm];
  if (ua && entry.unit_map[ua]) return entry.unit_map[ua];
  // First available
  return Object.values(entry.unit_map)[0];
}

