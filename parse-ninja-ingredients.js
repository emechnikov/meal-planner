const data = JSON.parse(fs.readFileSync(RECIPES_FILE, 'utf8'));
const recipes = data.recipes || [];

let converted = 0, skipped = 0;

recipes.forEach(recipe => {
  // Только рецепты с пустыми ingredients и непустым ingredients_text
  if (!recipe.ingredients_text || (recipe.ingredients && recipe.ingredients.length > 0)) return;

  const lines = recipe.ingredients_text
    .split('\n')
    .map(l => l.trim())
    .filter(l => l.length > 3);

  const structured = [];

  lines.forEach(line => {
    const parsed = parseLine(line);
    if (!parsed) return;

    const entry = findPrice(parsed.name);
    let prices = { lidl: 0, continente: 0, pingo_doce: 0 };
    let category = '🥫 Бакалея';

    if (entry) {
      const up = getUnitPrice(entry, parsed.unit);
      if (up) {
        prices = {
          lidl: +Math.abs(up[0] * parsed.amount).toFixed(2),
          continente: +Math.abs(up[1] * parsed.amount).toFixed(2),
          pingo_doce: +Math.abs(up[2] * parsed.amount).toFixed(2),
        };
      }
      category = entry.cat;
    }

    // Чистим название от скобок с пояснением
    const cleanName = parsed.name
      .replace(/\(отбитых?\)/gi, '')
      .replace(/\(.*?\)/g, '')
      .replace(/нарезать.+/gi, '')
      .replace(/\s+/g, ' ')
      .trim();

    structured.push({
      name: cleanName,
      amount: parsed.amount,
      unit: parsed.unit,
      category,
      prices
    });
  });

  if (structured.length > 0) {
    recipe.ingredients = structured;
    converted++;
  } else {
    skipped++;
  }
});

data.recipes = recipes;
data.total = recipes.length;
fs.writeFileSync(RECIPES_FILE, JSON.stringify(data, null, 2));

