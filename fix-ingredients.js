function canonicalize(name) {
  const low = name.toLowerCase().trim().replace(/\s+/g, ' ');
  // Убираем скобочные пояснения: "Масло сливочное (растопленное)" → "Масло сливочное"
  const withoutParens = low.replace(/\s*\([^)]*\)/, '').trim();
  return CANONICAL[withoutParens] || CANONICAL[low] || null;
}

// ── ПАРСЕР СТРОКИ ИНГРЕДИЕНТА ──────────────────────────────────────────────
const FRACTIONS = {'½':0.5,'¼':0.25,'¾':0.75,'⅓':0.33,'⅔':0.67,'⅛':0.125};
const UNITS = ['ст\\.л\\.','ч\\.л\\.','кг','мл','л','г','шт','зуб\\.','банка','банок','банки','пачка','лист','листа','ломт','полоск'];
const UNIT_RX = new RegExp(`^(\\d+(?:[.,]\\d+)?)\\s*(${UNITS.join('|')})\\.?\\s+(.+)$`,'i');
const NUM_RX = /^(\d+(?:[.,]\d+)?)\s+(.+)$/;

function parseSingleLine(raw) {
  let text = raw.trim();
  // Заменяем дроби
  for (const [f,v] of Object.entries(FRACTIONS)) text = text.replace(f, v+' ');
  text = text.replace(/\s+/g,' ').trim();

  let m = text.match(UNIT_RX);
  if (m) return { amount: parseFloat(m[1].replace(',','.')), unit: m[2].replace(/\\/g,''), nameRaw: m[3].trim() };

  m = text.match(NUM_RX);
  if (m) return { amount: parseFloat(m[1]), unit: 'шт', nameRaw: m[2].trim() };

  return { amount: 1, unit: 'по вкусу', nameRaw: text };
}

// ── ОПРЕДЕЛИТЬ: составная строка-описание? ────────────────────────────────
// "Ванильный соус: 200мл молока + ..."  — да
// "Подача: мороженое или сливки"        — да (метка "подача")
// Признаки: содержит " + ", или начинается с заглавного слова + ":", или "Подача:"
function isCompoundDescription(name) {
  const n = name.trim();
  // Явная составная: "Что-то: ..."
  if (/^[А-ЯA-Z][^:]+:\s*.{10,}/.test(n)) return true;
  // Содержит " + " с несколькими частями
  if (n.includes(' + ') && n.split(' + ').length >= 3) return true;
  return false;
}

// Разобрать составную строку на отдельные ингредиенты
function expandCompound(name, unit, defaultCategory) {
  // Убираем префикс "Ванильный соус: "
  let body = name.replace(/^[^:]+:\s*/, '');
  // Разбиваем по " + "
  const parts = body.split(/\s*\+\s*/).map(p => p.trim()).filter(p => p.length > 2);
  return parts.map(part => {
    const parsed = parseSingleLine(part);
    return {
      name: capitalizeFirst(parsed.nameRaw),
      amount: parsed.amount,
      unit: parsed.unit,
      category: defaultCategory || '🥫 Бакалея',
      prices: { lidl: 0, continente: 0, pingo_doce: 0 }
    };
  });
}

// Описания подачи/украшения — не нужны в корзине
function isServingNote(name) {
  const low = name.toLowerCase();
  return low.startsWith('подача') || low.startsWith('для подачи') ||
         low.startsWith('украшение') || low.startsWith('гарнир:') ||
         low.startsWith('по желанию') || low.startsWith('опционально');
}

function capitalizeFirst(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

// ── ПРИМЕНЯЕМ ФИКСЫ ────────────────────────────────────────────────────────
let fixedNames = 0, expandedCompound = 0, removedNotes = 0;

data.recipes = data.recipes.map(recipe => {
  if (!recipe.ingredients || !recipe.ingredients.length) return recipe;

  const newIngredients = [];

  recipe.ingredients.forEach(ing => {
    const name = ing.name || '';

    // 1. Удаляем заметки подачи
    if (isServingNote(name)) { removedNotes++; return; }

    // 2. Составные строки → разбиваем
    if (isCompoundDescription(name)) {
      const expanded = expandCompound(name, ing.unit, ing.category);
      if (expanded.length > 0) {
        newIngredients.push(...expanded);
        expandedCompound++;
        return;
      }
    }

    // 3. Нормализуем имя
    const canonical = canonicalize(name);
    if (canonical && canonical !== name) {
      ing = { ...ing, name: canonical };
      fixedNames++;
    } else if (!canonical) {
      // Чистим скобочные пояснения если имя длинное
      const cleaned = name.replace(/\s*\(.*?\)/g, '').trim();
      if (cleaned.length > 3 && cleaned !== name) {
        ing = { ...ing, name: capitalizeFirst(cleaned) };
        fixedNames++;
      }
    }

    newIngredients.push(ing);
  });

  return { ...recipe, ingredients: newIngredients };
});

