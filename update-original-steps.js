// Fallback улучшенный шаг для рецептов без ручного описания
function improveSteps(recipe) {
  const orig = recipe.steps || '';
  // Если уже подробный (Ninja) — не трогаем
  if (orig.length > 400) return orig;

  const lines = orig.split('\n').filter(Boolean);

  // Добавляем температуры и пояснения к существующим шагам
  return lines.map((line, i) => {
    let improved = line;
    // AF температуры
    improved = improved.replace(/AF\s*(\d+)°C\s*[—–-]\s*(\d+)/g, 'AF $1°C — $2 мин');
    // Добавить конкретику к расплывчатым шагам
    if (improved.match(/вари\s+\d+[-–]\d+/)) {
      improved = improved.replace(/вари\s+(\d+)[-–](\d+)\s*мин/, 'вари $1–$2 мин на среднем огне, периодически помешивая');
    }
    return improved;
  }).join('\n');
}

